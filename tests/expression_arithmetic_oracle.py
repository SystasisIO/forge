#!/usr/bin/env python3
"""Reproduce exact math.mul_div fixtures with Python integers and Fraction."""

import argparse
from fractions import Fraction
from math import ceil, floor
from pathlib import Path
import random


def expectation(unsigned_values, left, right, divisor, mode):
    if mode not in range(4) or divisor == 0:
        return 1, ""
    value = Fraction(left * right, divisor)
    result = (int, floor, ceil, round)[mode](value)
    lower = 0 if unsigned_values else -(1 << 63)
    upper = (1 << (64 if unsigned_values else 63)) - 1
    if not lower <= result <= upper:
        return 2, ""
    return 0, str(result)


def render():
    minimum, maximum, unsigned_maximum = -(1 << 63), (1 << 63) - 1, (1 << 64) - 1
    signed = [
        (0, 0, 1), (0, 1, -1), (1, 0, minimum), (0, 0, 0), (1, 1, 0),
        (10**15, 10**15, 10**15), (10**15, 9999, 10000),
        (minimum, minimum, minimum), (minimum, -1, 1), (minimum, -1, 2),
        (minimum, 1, 1), (maximum, 2, 2), (maximum, 2, 1),
        (6148914691236517205, 3, 2), (-274177, 67280421310721, 2),
        (minimum, 1, 3), (maximum, 1, minimum), (1, 1, minimum),
    ]
    for left in (-7, -5, -3, -1, 1, 3, 5, 7):
        for right in (-1, 1):
            for divisor in (-3, -2, 2, 3):
                signed.append((left, right, divisor))
    unsigned = [
        (0, 0, 1), (0, 0, 0), (1, 1, 0), (1, 1, 1),
        (10**15, 10**15, 10**15), (10**15, 9999, 10000),
        (unsigned_maximum, unsigned_maximum, unsigned_maximum),
        (unsigned_maximum, unsigned_maximum, 1),
        (unsigned_maximum, 2, 2), (31, 1190112520884487201, 2),
    ]
    for left in (1, 3, 5, 7, unsigned_maximum):
        for divisor in (2, 3, unsigned_maximum):
            unsigned.append((left, 1, divisor))

    rng = random.Random(0x464F524745)
    for _ in range(128):
        signed.append(tuple(rng.randrange(minimum, maximum + 1) for _ in range(3)))
        unsigned.append(tuple(rng.randrange(unsigned_maximum + 1) for _ in range(3)))

    lines = [
        "// Generated by expression_arithmetic_oracle.py; do not edit.",
        "// Python Fraction oracle, deterministic random seed 0x464f524745.",
        "// Fields: unsigned_values, left, right, divisor, mode, status, result.",
        "// Backend-neutral status: 0 success, 1 invalid argument, 2 overflow.",
    ]
    for unsigned_values, triples in ((False, signed), (True, unsigned)):
        for left, right, divisor in triples:
            for mode in range(4):
                status, value = expectation(unsigned_values, left, right, divisor, mode)
                lines.append(
                    f'{{{str(unsigned_values).lower()}, "{left}", "{right}", "{divisor}", '
                    f'{mode}, {status}, "{value}"}},'
                )
        for mode in (-1, 4, minimum, maximum):
            status, value = expectation(unsigned_values, 1, 1, 1, mode)
            mode_literal = "(-9223372036854775807LL - 1)" if mode == minimum else str(mode)
            lines.append(
                f'{{{str(unsigned_values).lower()}, "1", "1", "1", '
                f'{mode_literal}, {status}, "{value}"}},'
            )
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify existing fixtures without rewriting them")
    options = parser.parse_args()
    output = Path(__file__).with_name("expression_arithmetic_cases.inc")
    expected = render()
    if options.check:
        if not output.is_file() or output.read_text() != expected:
            raise SystemExit("arithmetic oracle fixtures are stale")
    else:
        output.write_text(expected)
    print(f"{len(expected.splitlines()) - 4} exact arithmetic oracle cases verified")


if __name__ == "__main__":
    main()
