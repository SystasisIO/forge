template <typename T> T checked(llvm::Expected<T> value) {
   if (!value) {
      llvm::consumeError(value.takeError());
      FORGE_THROW_EXCEPTION(optimizing::exceptions::compiler_unavailable, "LLVM object metadata is malformed");
   }
   return std::move(*value);
}

std::uint64_t add_offset(std::uint64_t offset, std::int64_t addend) {
   if (addend < 0) {
      // Avoid negating INT64_MIN in a signed type.
      const auto magnitude = std::uint64_t{0} - static_cast<std::uint64_t>(addend);
      if (magnitude > offset)
         FORGE_THROW_EXCEPTION(optimizing::exceptions::compiler_unavailable,
                               "LLVM symbol addend is outside its section");
      return offset - magnitude;
   }
   if (static_cast<std::uint64_t>(addend) > UINT64_MAX - offset)
      FORGE_THROW_EXCEPTION(optimizing::exceptions::compiler_unavailable, "LLVM symbol addend overflows");
   return offset + static_cast<std::uint64_t>(addend);
}
