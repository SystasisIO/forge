void object_image::normalize(std::span<const std::uint8_t> bytes, optimizing::artifact_payload& payload) {
   auto object = checked(llvm::object::ObjectFile::createObjectFile(
       llvm::MemoryBufferRef{{reinterpret_cast<const char*>(bytes.data()), bytes.size()}, "forge_wasm_object"}));
   const auto* elf = llvm::dyn_cast<llvm::object::ELF64LEObjectFile>(object.get());
   const auto arm64 = payload.configuration.target.triple == "aarch64-apple-macosx11.0.0-elf";
   const auto machine = arm64 ? llvm::ELF::EM_AARCH64 : llvm::ELF::EM_X86_64;
   if (!elf || elf->getELFFile().getHeader().e_machine != machine ||
       elf->getELFFile().getHeader().e_type != llvm::ELF::ET_REL)
      FORGE_THROW_EXCEPTION(optimizing::exceptions::unsupported_target,
                            "LLVM did not emit the selected 64-bit little-endian ELF object");

   auto image_indices = std::map<std::uint64_t, std::uint32_t>{};
   auto stack_sections = std::map<std::uint64_t, llvm::object::SectionRef>{};
   auto generated_bytes = std::uint64_t{0};
   for (const auto& section : object->sections()) {
      const auto name = checked(section.getName());
      if (name == ".stack_sizes") {
         stack_sections.emplace(section.getIndex(), section);
         continue;
      }
      const auto elf_section = llvm::object::ELFSectionRef{section};
      if (!(elf_section.getFlags() & llvm::ELF::SHF_ALLOC))
         continue;
      if (elf_section.getFlags() & (llvm::ELF::SHF_WRITE | llvm::ELF::SHF_TLS | llvm::ELF::SHF_COMPRESSED) ||
          elf_section.getType() != llvm::ELF::SHT_PROGBITS)
         FORGE_THROW_EXCEPTION(optimizing::exceptions::compiler_unavailable,
                               "LLVM emitted unsupported mutable or special image storage");
      const auto contents = checked(section.getContents());
      if (contents.empty())
         continue;
      if (contents.size() > payload.configuration.limits.max_generated_bytes - generated_bytes)
         FORGE_THROW_EXCEPTION(optimizing::exceptions::compile_limit, "LLVM object exceeds its generated byte budget");
      generated_bytes += contents.size();
      const auto index = static_cast<std::uint32_t>(payload.sections.size());
      image_indices.emplace(section.getIndex(), index);
      payload.sections.push_back(
          {section.isText() ? optimizing::section_kind::code : optimizing::section_kind::readonly_data,
           section.getAlignment().value(),
           {contents.bytes_begin(), contents.bytes_end()}});
   }

   const auto location = [&](llvm::object::SymbolRef symbol) {
      const auto section = checked(symbol.getSection());
      if (section == object->section_end() || !image_indices.contains(section->getIndex()))
         FORGE_THROW_EXCEPTION(optimizing::exceptions::compiler_unavailable,
                               "LLVM object refers to an external or excluded symbol");
      const auto index = image_indices.at(section->getIndex());
      const auto offset = checked(symbol.getValue());
      if (offset > payload.sections[index].bytes.size())
         FORGE_THROW_EXCEPTION(optimizing::exceptions::compiler_unavailable,
                               "LLVM symbol is outside its native image section");
      return optimizing::image_location{index, offset};
   };
   auto function_names = std::map<std::string, std::uint32_t>{};
   for (std::uint32_t i = 0; i < payload.functions.size(); ++i)
      function_names.emplace("forge_wasm_" + std::to_string(i), i);
   auto function_locations = std::map<std::pair<std::uint32_t, std::uint64_t>, std::uint32_t>{};
   auto seen_functions = std::set<std::uint32_t>{};
   for (const auto& symbol : object->symbols()) {
      const auto type = checked(symbol.getType());
      if (type != llvm::object::SymbolRef::ST_Function)
         continue;
      const auto name = checked(symbol.getName()).str();
      const auto found = function_names.find(name);
      if (found == function_names.end() || !seen_functions.insert(found->second).second)
         FORGE_THROW_EXCEPTION(optimizing::exceptions::compiler_unavailable,
                               "LLVM emitted an unknown or duplicate native function");
      const auto entry = location(symbol);
      if (payload.sections[entry.section].kind != optimizing::section_kind::code ||
          entry.offset >= payload.sections[entry.section].bytes.size() ||
          !function_locations.emplace(std::pair{entry.section, entry.offset}, found->second).second)
         FORGE_THROW_EXCEPTION(optimizing::exceptions::compiler_unavailable,
                               "LLVM function entries are invalid or aliased");
      payload.functions[found->second].entry = entry;
   }
   if (seen_functions.size() != payload.functions.size())
      FORGE_THROW_EXCEPTION(optimizing::exceptions::compiler_unavailable,
                            "LLVM emitted incomplete function entry metadata");

   // .stack_sizes address relocations identify a function exactly. They are
   // metadata, not relocations copied into the executable image.
   auto frame_addresses = std::map<std::pair<std::uint64_t, std::uint64_t>, optimizing::image_location>{};
   for (const auto& relocation_section : object->sections()) {
      const auto relocated = checked(relocation_section.getRelocatedSection());
      if (relocated == object->section_end())
         continue;
      const auto source_index = relocated->getIndex();
      const auto is_frame = stack_sections.contains(source_index);
      if (!is_frame && !image_indices.contains(source_index)) {
         if (relocation_section.relocation_begin() != relocation_section.relocation_end())
            FORGE_THROW_EXCEPTION(optimizing::exceptions::compiler_unavailable,
                                  "LLVM emitted relocations for excluded storage");
         continue;
      }
      if (llvm::object::ELFSectionRef{relocation_section}.getType() != llvm::ELF::SHT_RELA)
         FORGE_THROW_EXCEPTION(optimizing::exceptions::compiler_unavailable,
                               "LLVM emitted unsupported relocation encoding");
      for (const auto& relocation : relocation_section.relocations()) {
         const auto symbol = relocation.getSymbol();
         if (symbol == object->symbol_end())
            FORGE_THROW_EXCEPTION(optimizing::exceptions::compiler_unavailable, "LLVM relocation lacks a symbol");
         auto target = location(*symbol);
         const auto addend = checked(llvm::object::ELFRelocationRef{relocation}.getAddend());
         if (is_frame) {
            target.offset = add_offset(target.offset, addend);
            const auto address_type = arm64 ? static_cast<std::uint64_t>(llvm::ELF::R_AARCH64_ABS64)
                                           : static_cast<std::uint64_t>(llvm::ELF::R_X86_64_64);
            if (relocation.getType() != address_type ||
                !function_locations.contains({target.section, target.offset}) ||
                !frame_addresses.emplace(std::pair{source_index, relocation.getOffset()}, target).second)
               FORGE_THROW_EXCEPTION(optimizing::exceptions::compiler_unavailable,
                                     "LLVM stack metadata has invalid address relocations");
            continue;
         }
         auto kind = optimizing::relocation_kind{};
         if (arm64) {
            switch (relocation.getType()) {
            case llvm::ELF::R_AARCH64_ABS64: kind = optimizing::relocation_kind::absolute64; break;
            case llvm::ELF::R_AARCH64_PREL32: kind = optimizing::relocation_kind::relative32; break;
            case llvm::ELF::R_AARCH64_CALL26: kind = optimizing::relocation_kind::aarch64_call26; break;
            case llvm::ELF::R_AARCH64_JUMP26: kind = optimizing::relocation_kind::aarch64_jump26; break;
            case llvm::ELF::R_AARCH64_ADR_PREL_PG_HI21: kind = optimizing::relocation_kind::aarch64_page21; break;
            case llvm::ELF::R_AARCH64_ADD_ABS_LO12_NC: kind = optimizing::relocation_kind::aarch64_add12; break;
            case llvm::ELF::R_AARCH64_LDST8_ABS_LO12_NC: kind = optimizing::relocation_kind::aarch64_load_store8; break;
            case llvm::ELF::R_AARCH64_LDST16_ABS_LO12_NC: kind = optimizing::relocation_kind::aarch64_load_store16; break;
            case llvm::ELF::R_AARCH64_LDST32_ABS_LO12_NC: kind = optimizing::relocation_kind::aarch64_load_store32; break;
            case llvm::ELF::R_AARCH64_LDST64_ABS_LO12_NC: kind = optimizing::relocation_kind::aarch64_load_store64; break;
            default:
               FORGE_THROW_EXCEPTION(optimizing::exceptions::compiler_unavailable,
                                     "LLVM emitted an unsupported AArch64 relocation");
            }
         } else switch (relocation.getType()) {
         case llvm::ELF::R_X86_64_64:
            kind = optimizing::relocation_kind::absolute64;
            break;
         case llvm::ELF::R_X86_64_PC32:
         case llvm::ELF::R_X86_64_PLT32:
            kind = optimizing::relocation_kind::relative32;
            break;
         default:
            FORGE_THROW_EXCEPTION(optimizing::exceptions::compiler_unavailable,
                                  "LLVM emitted an unsupported native relocation");
         }
         payload.relocations.push_back(
             {kind, {image_indices.at(source_index), relocation.getOffset()}, target, addend});
      }
   }
   auto seen_frames = std::set<std::uint32_t>{};
   auto consumed_addresses = std::size_t{0};
   for (const auto& [section_index, section] : stack_sections) {
      const auto contents = checked(section.getContents());
      const auto* start = reinterpret_cast<const std::uint8_t*>(contents.data());
      const auto* end = start + contents.size();
      auto offset = std::uint64_t{0};
      while (offset < contents.size()) {
         const auto address = frame_addresses.find({section_index, offset});
         if (contents.size() - offset < 8 || address == frame_addresses.end())
            FORGE_THROW_EXCEPTION(optimizing::exceptions::compiler_unavailable,
                                  "LLVM stack metadata lacks a complete function address");
         offset += 8;
         auto length = unsigned{0};
         const char* error = nullptr;
         const auto frame = llvm::decodeULEB128(start + offset, &length, end, &error);
         if (error || !length || frame > UINT64_MAX - 8)
            FORGE_THROW_EXCEPTION(optimizing::exceptions::compiler_unavailable,
                                  "LLVM stack metadata has no fixed bounded frame");
         offset += length;
         const auto index = function_locations.at({address->second.section, address->second.offset});
         if (!seen_frames.insert(index).second)
            FORGE_THROW_EXCEPTION(optimizing::exceptions::compiler_unavailable,
                                  "LLVM emitted duplicate function stack metadata");
         // AArch64 stores LR in a register; any spilled LR is already in the
         // fixed, 16-byte aligned frame. x86's incoming return address is not.
         if (arm64 && frame % 16 != 0)
            FORGE_THROW_EXCEPTION(optimizing::exceptions::compiler_unavailable,
                                  "LLVM emitted a misaligned AArch64 fixed frame");
         const auto bytes_per_call = frame + (arm64 ? 0 : 8);
         if (bytes_per_call > payload.configuration.limits.max_function_stack_bytes)
            FORGE_THROW_EXCEPTION(optimizing::exceptions::compile_limit,
                                  "LLVM function exceeds its admitted frame budget");
         payload.functions[index].stack_bytes = bytes_per_call;
         ++consumed_addresses;
      }
   }
   if (seen_frames.size() != payload.functions.size() || consumed_addresses != frame_addresses.size())
      FORGE_THROW_EXCEPTION(optimizing::exceptions::compiler_unavailable,
                            "LLVM emitted missing or unmatched stack metadata");
}

